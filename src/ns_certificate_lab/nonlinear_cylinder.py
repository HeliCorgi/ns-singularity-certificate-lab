r"""Production nonlinear finite-cylinder integrator for ``(u_1, omega_1, psi_1)``.

The audited system (``docs/equation_audit.md``, E-11--E-14) is

.. math::

   \partial_t u_1 + u^r u_{1,r} + u^z u_{1,z}
       &= 2 u_1 \psi_{1,z} + \nu \mathcal L_5 u_1 + F_{u_1},\\
   \partial_t \omega_1 + u^r \omega_{1,r} + u^z \omega_{1,z}
       &= \partial_z(u_1^2) + \nu \mathcal L_5 \omega_1 + F_{\omega_1},\\
   -\mathcal L_5 \psi_1 &= \omega_1,\qquad
   \mathcal L_5 = \partial_{rr} + \tfrac{3}{r}\partial_r + \partial_{zz},\\
   u^r &= -r\psi_{1,z},\qquad u^z = 2\psi_1 + r\psi_{1,r}.

The geometry is the Hou finite cylinder: ``0 <= r <= r_max`` (production
``r_max = 1``), full period in ``z``, wall conditions E-27 at ``r = r_max``.
``F_{u_1}`` and ``F_{\omega_1}`` are manufactured forcings used only by the
verification tests; production runs use ``None``.

Stage ordering (identical in every Heun stage; ``n_r-1`` is the wall row)
--------------------------------------------------------------------------

Every state pair ``(u_1, \omega_1)`` produced by an update is immediately
mapped to a *constrained* state by :func:`constrain_state`, in this order:

1. ``u_1[n_r-1, :] = 0``                       (E-27 no-slip swirl trace).
2. ``psi_1 = solve_streamfunction_poisson(omega_1, g = 0)``   (E-13 with the
   single Dirichlet condition ``psi_1(r_max, z) = 0`` of E-27; imposing
   ``psi_{1,r} = 0`` as well would over-determine the elliptic problem).
3. ``omega_1[n_r-1, :] = -(8 psi_1[n_r-2, :] - psi_1[n_r-3, :])/(2 dr^2)``
   (E-31, second-order Thom-type wall vorticity).
4. ``u^r, u^z`` are recovered from ``psi_1`` by E-14.

Step 2 precedes step 3, and that ordering is *exact* rather than a lagged
approximation: solver A eliminates the outer Dirichlet unknown and builds its
right-hand side from radial rows ``0 .. n_r-2`` only, so the wall row of
``omega_1`` never enters the elliptic solve.  Re-solving after step 3 would
return the identical ``psi_1``; the constrained state is a fixed point of the
map.

The right-hand side (:func:`right_hand_side`) is evaluated from a constrained
state and its wall rows are set to zero, because both wall rows are algebraic
constraints rather than evolution equations.  Consequently every Heun update
leaves the wall rows untouched and they are regenerated by the next
:func:`constrain_state` call.

Time-step policy and the meaning of the recorded CFL number
------------------------------------------------------------

:func:`adaptive_time_step` evaluates the advective bound

.. math::

   dt \le C \min\!\big(dr/\max|u^r|,\ dz/\max|u^z|\big)

at the **start** of the step, from the state that is about to be advanced.
:func:`compute_diagnostics` instead reports ``advective_cfl`` as
``dt * max(max|u^r|/dr, max|u^z|/dz)`` measured on the state that the step
**produced**.  The two agree exactly when the meridional velocities do not
change during the step, because ``max(u/h)`` is the reciprocal of
``min(h/u)``; the recorded *effective* CFL therefore equals ``C`` times the
one-step relative growth of the dominant directional velocity ratio whenever
the advective bound is the active constraint.  It can consequently exceed
``C`` by exactly that growth factor.  The clipping of ``dt`` to snapshot,
viscosity-switch and ``t_final`` targets and the ``max_time_step`` cap can
only shrink ``dt``, so neither can raise the effective CFL above this bound.
The delegated numerical-method guidance recorded in
``docs/hou_setup_audit.md`` (HH21, arXiv:2102.06663 Appendix A) pairs the
CFL number ``0.1`` with a one-step relative growth of the maximum below one
percent, which bounds the excess.  In the shipped ``outputs/hou_early_time_v1``
run the largest recorded effective CFL was ``0.10022676304450114`` against
``cfl_coefficient = 0.1``, i.e. an excess of ``0.23`` percent (0.0022676),
well inside that one-percent guidance.  The experiment therefore accepts the
effective CFL against ``C * (1 + cfl_excess_tolerance)`` rather than against
``C`` itself; see ``experiments/run_hou_early_time.py``.

Relativized constraint diagnostics (TM-09)
------------------------------------------------------------

``docs/threat_model.md`` TM-09 warns that a small residual computed as the
difference of large terms says nothing on its own.  :func:`compute_diagnostics`
therefore reports the E-02 divergence residual and the E-16c axis parity defect
*both* absolutely and divided by their own cancellation scales
(:func:`relative_divergence`, :func:`relative_axis_parity`), together with the
denominators themselves and the grid locations of the maxima.  These relative
numbers are recorded, not gated.

Recorded deviations from ``docs/nonlinear_solver_design.md``
------------------------------------------------------------

* :func:`adaptive_time_step` accepts an optional ``max_time_step`` cap that the
  design does not list.  It is required because the design rule alone returns
  the viscous bound ``C min(dr,dz)^2/(4 nu)`` whenever the meridional velocity
  vanishes, and the E-29 initial datum has ``u^r = u^z = 0`` exactly; on a
  ``129 x 256`` grid with ``nu = 5e-4`` that first step is ``7.6e-4``, roughly a
  third of the whole early-time target window.  The cap is optional, defaults to
  absent, and never enlarges a step.
* The design's fault list includes "ignore the viscosity switch"; that path is
  covered here by direct assertions on :func:`viscosity_at` and on the switch
  times recorded by :func:`integrate` rather than by an injected fault.

The ``fault`` arguments exist only so that rejection tests can prove the
acceptance criteria are able to fail.  Production runs must pass ``None``.

Nothing in this module is a proof, an interval enclosure, or evidence for
singularity formation.  It is a floating-point candidate generator whose
snapshots are meant to be re-examined by the independent verification path
(solver B in :mod:`ns_certificate_lab.finite_cylinder_poisson`,
:mod:`ns_certificate_lab.pde` residuals, the Cartesian adapter).
"""

