@dataclass(frozen=True)
class IntegrationResult:
    """Final state, diagnostic history and step bookkeeping of one run."""

    grid: AxisymmetricGrid
    state: ConstrainedState
    time: float
    step_count: int
    history: tuple[dict[str, float], ...]
    snapshot_times: tuple[float, ...]
    viscosity_switch_times: tuple[float, ...]
    reference_vorticity_max: float
    completed: bool


def _step_targets(
    *,
    initial_time: float,
    t_final: float,
    schedule: tuple[tuple[float, float], ...],
    snapshot_times: Sequence[float],
) -> tuple[float, ...]:
    values = {float(t_final)}
    for switch_time, _ in schedule:
        if initial_time + _TIME_TOLERANCE < switch_time < t_final - _TIME_TOLERANCE:
            values.add(float(switch_time))
    for raw in snapshot_times:
        moment = float(raw)
        if not math.isfinite(moment):
            raise ValueError("snapshot times must be finite")
        if moment < initial_time - _TIME_TOLERANCE or moment > t_final + _TIME_TOLERANCE:
            raise ValueError("snapshot times must lie in [initial_time, t_final]")
        if moment > initial_time + _TIME_TOLERANCE:
            values.add(min(moment, float(t_final)))
    return tuple(sorted(values))


def integrate(
    grid: AxisymmetricGrid,
    *,
    u1: npt.ArrayLike,
    omega1: npt.ArrayLike,
    t_final: float,
    viscosity_schedule: Sequence[Sequence[float]],
    initial_time: float = 0.0,
    cfl_coefficient: float = 0.1,
    fixed_time_step: float | None = None,
    max_time_step: float | None = None,
    max_steps: int = 1_000_000,
    snapshot_times: Sequence[float] = (),
    forcing_u1: Forcing = None,
    forcing_omega1: Forcing = None,
    fault: Fault | None = None,
    diagnostic_stride: int = 1,
    on_snapshot: Callable[[float, ConstrainedState, dict[str, float]], None] | None = None,
    reference_vorticity_max: float | None = None,
) -> IntegrationResult:
    """Integrate E-11/E-12 from ``initial_time`` to ``t_final``.

    ``fixed_time_step`` selects the uniform-step mode used by convergence
    tests; otherwise the adaptive rule of :func:`adaptive_time_step` applies and
    steps are clipped so that viscosity switch times, snapshot times and
    ``t_final`` are hit exactly.
    """

    _check_fault(fault)
    schedule = normalize_viscosity_schedule(viscosity_schedule)
    start = float(initial_time)
    stop = float(t_final)
    if not (math.isfinite(start) and math.isfinite(stop)) or stop <= start:
        raise ValueError("t_final must be finite and greater than initial_time")
    if isinstance(max_steps, bool) or not isinstance(max_steps, int) or max_steps < 1:
        raise ValueError("max_steps must be a positive integer")
    if (
        isinstance(diagnostic_stride, bool)
        or not isinstance(diagnostic_stride, int)
        or diagnostic_stride < 1
    ):
        raise ValueError("diagnostic_stride must be a positive integer")

    targets = _step_targets(
        initial_time=start,
        t_final=stop,
        schedule=schedule,
        snapshot_times=snapshot_times,
    )
    requested_snapshots = tuple(
        sorted(
            {
                float(value)
                for value in snapshot_times
                if math.isfinite(float(value))
            }
        )
    )

    uniform_dt: float | None = None
    if fixed_time_step is not None:
        requested = float(fixed_time_step)
        if not math.isfinite(requested) or requested <= 0.0:
            raise ValueError("fixed_time_step must be positive and finite")
        step_count = max(1, math.ceil((stop - start) / requested))
        uniform_dt = (stop - start) / step_count
        for target in targets:
            offset = (target - start) / uniform_dt
            if abs(offset - round(offset)) > 1.0e-9 * max(1.0, abs(offset)):
                raise ValueError(
                    "fixed_time_step mode requires switch and snapshot times on "
                    "step boundaries"
                )

    state = constrain_state(grid, u1, omega1, fault=fault)
    reference = (
        float(reference_vorticity_max)
        if reference_vorticity_max is not None
        else float(
            np.max(
                np.sqrt(
                    sum(
                        component * component
                        for component in cartesian_vorticity(
                            grid, state.u1, state.omega1
                        )
                    )
                )
            )
        )
    )
    time = start
    history: list[dict[str, float]] = []
    recorded = compute_diagnostics(
        grid,
        state,
        time=time,
        dt=0.0,
        viscosity=viscosity_at(schedule, time),
        step=0,
        reference_vorticity_max=reference,
    )
    history.append(recorded)
    if on_snapshot is not None and any(
        abs(time - value) <= _TIME_TOLERANCE for value in requested_snapshots
    ):
        on_snapshot(time, state, recorded)

    switch_times: list[float] = []
    step_index = 0
    target_index = 0
    completed = False
    while target_index < len(targets):
        target = targets[target_index]
        while time < target - _TIME_TOLERANCE:
            if step_index >= max_steps:
                break
            nu = viscosity_at(schedule, time)
            if uniform_dt is not None:
                dt = uniform_dt
            else:
                dt = adaptive_time_step(
                    grid,
                    state,
                    viscosity=nu,
                    cfl_coefficient=cfl_coefficient,
                    max_time_step=max_time_step,
                )
            landed = False
            if dt >= target - time - _TIME_TOLERANCE:
                dt = target - time
                landed = True
            state = heun_step(
                grid,
                state,
                dt=dt,
                time=time,
                viscosity=nu,
                forcing_u1=forcing_u1,
                forcing_omega1=forcing_omega1,
                fault=fault,
            )
            time = target if landed else time + dt
            step_index += 1
            if not (
                np.all(np.isfinite(state.u1)) and np.all(np.isfinite(state.omega1))
            ):
                raise FloatingPointError("nonlinear cylinder state became non-finite")
            at_target = landed
            if step_index % diagnostic_stride == 0 or at_target:
                history.append(
                    compute_diagnostics(
                        grid,
                        state,
                        time=time,
                        dt=dt,
                        viscosity=nu,
                        step=step_index,
                        reference_vorticity_max=reference,
                    )
                )
        if time < target - _TIME_TOLERANCE:
            break
        if any(abs(target - value) <= _TIME_TOLERANCE for value in requested_snapshots):
            if on_snapshot is not None:
                on_snapshot(target, state, history[-1])
        if any(abs(target - switch) <= _TIME_TOLERANCE for switch, _ in schedule[1:]):
            switch_times.append(float(target))
        target_index += 1
    else:
        completed = True

    return IntegrationResult(
        grid=grid,
        state=state,
        time=time,
        step_count=step_index,
        history=tuple(history),
        snapshot_times=requested_snapshots,
        viscosity_switch_times=tuple(switch_times),
        reference_vorticity_max=reference,
        completed=completed,
    )


def checkpoint_description(
    *,
    physical_time: float,
    viscosity: float,
) -> dict[str, Any]:
    """Return the candidate v2 description block for a solver checkpoint."""

    return {
        "representation": (
            "transformed axisymmetric state (u1, omega1, psi1) on a uniform "
            "finite-cylinder grid with periodic z"
        ),
        "coordinate_system": "axisymmetric cylindrical half-plane (r, z)",
        "units": {
            "r": "dimensionless length",
            "z": "dimensionless length",
            "u1": "dimensionless inverse time (u^theta / r)",
            "omega1": "dimensionless inverse length inverse time (omega^theta / r)",
            "psi1": "dimensionless length inverse time (psi^theta / r)",
        },
        "normalization": (
            "Hou finite-cylinder normalization: r in [0,1], z period 1, "
            "u1 = u^theta/r, omega1 = omega^theta/r, psi1 = psi^theta/r"
        ),
        "physical_time": float(physical_time),
        "viscosity": float(viscosity),
        "basis_convention": (
            "nodal float64 values on the uniform (r, z) tensor grid, r-major, "
            "z endpoint omitted"
        ),
    }


def save_checkpoint(
    path: str | Path,
    *,
    grid: AxisymmetricGrid,
    state: ConstrainedState,
    time: float,
    viscosity: float,
    seed: int,
    config: Mapping[str, Any],
    provenance: Mapping[str, Any] | None = None,
    metadata: Mapping[str, Any] | None = None,
) -> CandidatePaths:
    """Write a candidate schema v2 checkpoint of ``(u1, omega1, psi1)``."""

    extra = dict(metadata or {})
    extra.setdefault("solver", "ns_certificate_lab.nonlinear_cylinder")
    extra.setdefault(
        "interpretation",
        "floating-point candidate snapshot; not a proof and not evidence of "
        "singularity formation",
    )
    extra.setdefault("physical_time", float(time))
    extra.setdefault("viscosity", float(viscosity))
    return save_candidate(
        path,
        grid=grid,
        fields={
            "u1": state.u1,
            "omega1": state.omega1,
            "psi1": state.psi1,
        },
        config=config,
        seed=seed,
        description=checkpoint_description(
            physical_time=float(time),
            viscosity=float(viscosity),
        ),
        metadata=extra,
        provenance=provenance,
    )


@dataclass(frozen=True)
class Checkpoint:
    """A restored checkpoint ready to resume."""

    grid: AxisymmetricGrid
    state: ConstrainedState
    time: float
    viscosity: float
    config: dict[str, Any]
    metadata: dict[str, Any]
    seed: int


def load_checkpoint(path: str | Path, *, fault: Fault | None = None) -> Checkpoint:
    """Load and re-constrain a checkpoint written by :func:`save_checkpoint`."""

    artifact = load_candidate(path)
    if artifact.description is None:
        raise ValueError("nonlinear cylinder checkpoints require a v2 description")
    if set(artifact.fields) != {"u1", "omega1", "psi1"}:
        raise ValueError("checkpoint must store exactly u1, omega1 and psi1")
    state = constrain_state(
        artifact.grid,
        artifact.fields["u1"],
        artifact.fields["omega1"],
        fault=fault,
    )
    return Checkpoint(
        grid=artifact.grid,
        state=state,
        time=float(artifact.description.physical_time),
        viscosity=float(artifact.description.viscosity),
        config=dict(artifact.config),
        metadata=dict(artifact.metadata),
        seed=int(artifact.seed),
    )


def resume(
    path: str | Path,
    *,
    t_final: float,
    viscosity_schedule: Sequence[Sequence[float]],
    **options: Any,
) -> IntegrationResult:
    """Resume :func:`integrate` from a saved checkpoint."""

    checkpoint = load_checkpoint(path, fault=options.get("fault"))
    return integrate(
        checkpoint.grid,
        u1=checkpoint.state.u1,
        omega1=checkpoint.state.omega1,
        t_final=t_final,
        viscosity_schedule=viscosity_schedule,
        initial_time=checkpoint.time,
        **options,
    )
