r"""Kinematic and far-field checks for a Zeno packet-relay candidate.

This module studies one deliberately narrow question.  Can a hierarchy of
spatially disjoint, Navier--Stokes-scaled packets evade the energy and total
dissipation obstructions while accumulating critical ``L^3`` mass?

For a fixed divergence-free template ``W`` and dyadic wavenumbers
``lambda_j = base**j``, the kinematic packet is

.. math::

   w_j(x) = \lambda_j W(\lambda_j(x-x_j)).

If the supports are disjoint, then its packet energy is proportional to
``lambda_j**-1`` while its ``L^3`` mass is independent of ``j``.  A stack of
``J+1`` packets therefore has bounded energy, enstrophy of order
``lambda_J``, and ``L^3`` mass of order ``J``.  This is the finite-low-frequency
floor that the historical positive-slope shell classifier did not model.

A compactly supported packet is not exactly band limited.  Consequently, the
packet sums and the modeled Littlewood--Paley shell sums computed here are two
separate kinematic checks.  Identifying them requires spectral-leakage bounds;
this module does not assume that bridge.

The module also evaluates the leading far-field pressure Hessian generated by
one packet.  If

.. math::

   M_{ij}=\int u_i u_j\,dx,

then outside the transmitter support

.. math::

   p(x)=M_{ij}\,\partial_i\partial_j(4\pi|x|)^{-1}+O(|x|^{-4}),

so ``Hess(p)`` is the fourth derivative of the Newtonian kernel and decays as
``distance**-5``.  The sign test here only establishes that a favourable
pressure-strain orientation is algebraically possible.  It does not establish
that Navier--Stokes dynamics creates, transports, or preserves the packet
stack.

Scientific status: **FORMAL ANSATZ / AUDIT REQUIRED**.  No function in this
module constructs a Navier--Stokes solution or proves blow-up.
"""

